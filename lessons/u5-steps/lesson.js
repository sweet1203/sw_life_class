/* 02 프로젝트 기획 순서 누르기 (177쪽 첫 문단) */
(function(){
  const ORD=['전체 업무를 나열해 구조화하기','업무별 담당자 정하기','업무의 순서와 일정 계획하기','일어날 수 있는 변수와 대비책 마련하기','진행 과정을 간략한 문서로 정리하기'];
  const B=$('stOrder'); let pos=0, tries=0, shuf;
  function start(){
    shuf=ORD.map((t,i)=>i).sort(()=>Math.random()-.5); if(shuf.every((x,i)=>x===i)) shuf.reverse(); pos=0; tries=0; draw('');
  }
  function draw(msg){
    const done=pos>=ORD.length;
    B.innerHTML='<div class="st-ord"><div class="q">'+(done?'모두 맞게 눌렀어요! 🎉':'다음에 할 일을 골라요 ('+(pos+1)+' / '+ORD.length+')')+'</div>'+
      '<div class="pool">'+shuf.filter(i=>i>=pos).map(i=>'<button type="button" data-i="'+i+'">'+ORD[i]+'</button>').join('')+'</div>'+
      '<ol>'+ORD.slice(0,pos).map((t,i)=>'<li><b>'+(i+1)+'</b> '+t+'</li>').join('')+'</ol>'+
      '<div class="fb" aria-live="polite">'+(done?'틀린 횟수 '+tries+'번 · 업무를 나열해 구조화 → 담당자 → 순서·일정 → 변수와 대비책 → 문서 정리 순이에요. <button type="button" class="btn ghost sm" id="stOrdAgain">다시 하기</button>':msg)+'</div></div>';
    B.querySelectorAll('.pool button').forEach(b=>b.onclick=()=>{
      const i=+b.dataset.i;
      if(i===pos){pos++; draw(pos<ORD.length?'좋아요! 그다음은 무엇일까요?':'');}
      else{tries++; draw('아직이에요. 교과서 문단에서 이 일은 조금 뒤에 나와요. 다시 골라 봐요.');}
    });
    const ag=$('stOrdAgain'); if(ag) ag.onclick=start;
  }
  start();
})();

