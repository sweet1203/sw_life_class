/* 04 가치 성찰 · 점수 합계 */
(function(){
  const el=k=>document.querySelector('[data-memo="'+k+'"]');
  const touched=new Set();
  const names=['사회적','기능적','윤리적'];
  const ks=[]; for(let i=0;i<3;i++){ks.push(['vlSc'+i,'vlOs'+i]);}
  ks.flat().forEach(k=>{ if(MEMO[k]!=null&&MEMO[k]!=='') touched.add(k); });
  function calc(){
    let tot=0, n=0; const parts=[];
    ks.forEach(([a,b],i)=>{
      const va=touched.has(a)?+el(a).value:null, vb=touched.has(b)?+el(b).value:null;
      $('vlSv'+i).textContent=va==null?'–':va+'점';
      $('vlOv'+i).textContent=vb==null?'–':vb+'점';
      const sub=(va||0)+(vb||0), c=(va==null?0:1)+(vb==null?0:1);
      $('vlSub'+i).textContent=c?names[i]+' 가치 합계 '+sub+'점 ('+c+'개 기준)':'';
      tot+=sub; n+=c; if(c) parts.push(names[i]+' '+sub);
    });
    $('vlTotal').innerHTML=n?'고른 기준 <b>'+n+'개</b> · 전체 합계 <b>'+tot+'점</b>'+(parts.length?'<br><span class="muted">'+parts.join(' + ')+'</span>':''):'슬라이더를 움직이면 합계가 나와요.';
  }
  ks.flat().forEach(k=>{ const e=el(k); e.addEventListener('input',()=>{touched.add(k); calc();}); });
  /* 저장된 값을 불러오는 순서와 상관없이 처음 한 번 더 계산 */
  setTimeout(calc,0); calc();
})();

