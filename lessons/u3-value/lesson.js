(function(){
  const D0=['기후위: 7','에너지: 6','대응: 5','배출량: 4','오늘: 3','탄소중립: 3','국내: 2','자리: 2','전환: 2','전체: 2','전력생산: 2','재생에너지: 2','발전: 2','원전: 2','포럼: 2','유럽: 1','가뭄: 1','태풍: 1','폭우: 1','이재민: 1','온실가스: 1','화석연료: 1'].join('\n');
  const COL=['#2f9a5a','#2f6fd0','#d0602f','#9b4fc4','#d64535','#1f2f4a','#c98a0a'];
  const box=$('vlCloud'), ta=$('vlDict'), mn=$('vlMin'), rd=$('vlRead');
  let order=null;
  function parse(){
    const m={};
    ta.value.split('\n').forEach(l=>{
      const r=l.trim().match(/^(.+?)\s*[:：=,\s]\s*(\d+)$/);
      if(r){const k=r[1].trim(); m[k]=(m[k]||0)+Math.min(+r[2],99);}
    });
    return Object.entries(m).sort((a,b)=>b[1]-a[1]);
  }
  function draw(){
    const min=+mn.value; $('vlMinV').textContent=min+'회 이상';
    const all=parse(), list=all.filter(e=>e[1]>=min);
    if(!list.length){box.innerHTML='<span style="font-weight:400;color:#5b6776;font-size:.95rem">보여 줄 단어가 없어요. 「단어: 횟수」 줄을 확인해 봐요.</span>'; rd.textContent=''; return;}
    const mx=list[0][1];
    let arr=list.map((e,i)=>({w:e[0],n:e[1],c:COL[i%COL.length]}));
    const ws=new Set(order||[]);
    if(!order||order.length!==arr.length||arr.some(e=>!ws.has(e.w))){
      order=[]; arr.forEach((e,i)=>{ if(i%2===0) order.push(e.w); else order.unshift(e.w); });
    }
    const pos=new Map(order.map((w,i)=>[w,i]));
    arr.sort((a,b)=>pos.get(a.w)-pos.get(b.w));
    box.innerHTML=arr.map(e=>`<span style="font-size:${(0.95+2.7*e.n/mx).toFixed(2)}rem;color:${e.c}">${esc(e.w)}</span>`).join('');
    const top=list.slice(0,3).map(e=>`<b>${esc(e[0])}</b>(${e[1]}번)`).join(', ');
    rd.innerHTML=`가장 크게 나온 단어: ${top}<br>그림에 나온 단어 <b>${list.length}개</b> · 횟수의 합 <b>${list.reduce((s,e)=>s+e[1],0)}번</b>`;
  }
  function fresh(){order=null; draw();}
  ta.value=D0;
  $('vlDraw').onclick=fresh;
  mn.addEventListener('input',()=>{order=null;draw();});
  $('vlMix').onclick=()=>{ if(!order) draw(); order=shuffle(order); draw(); };
  $('vlReset').onclick=()=>{ta.value=D0; mn.value=1; fresh();};
  ta.addEventListener('input',()=>{order=null;draw();});
  draw();
})();

